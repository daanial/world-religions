export function pt(locale: LocaleCode, key: string, vars?: Record<string, string | number>): string {
  let value = (locale === "fa" ? fa[key] : en[key]) || en[key] || key;
  for (const [name, replacement] of Object.entries(vars ?? {})) {
    value = value.replace(`{${name}}`, String(replacement));
  }
  return value;
}
